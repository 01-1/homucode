const NodeFS = require("node:fs");
const NodePath = require("node:path");
const {
  AndroidConfig,
  withAndroidColors,
  withAndroidManifest,
  withDangerousMod,
  withMainActivity,
} = require("expo/config-plugins");

// An activity, not an activity-alias: an alias always joins its target's task. Ships disabled;
// T3MadoHomuLauncherModule enables it while MadoHomu is on. Copies the finished MainActivity.

const ACTIVITY_CLASS = "MadoHomuActivity";
const LAUNCH_SURFACE = "madohomu";
const ICON = "ic_madohomu";
const ICON_BACKGROUND_COLOR = "madohomu_icon_background";
const REPORT_WINDOW_FOCUS = "T3MadoHomuLauncherModule.onActivityFocused(this)";
const REPORT_BACK = "T3MadoHomuLauncherModule.onActivityBackPressed(this)";
// Expo writes ic_launcher_foreground/_monochrome only for adaptive icons; derive from them.
const ADAPTIVE_ICON = `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/${ICON_BACKGROUND_COLOR}"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome"/>
</adaptive-icon>
`;
// Below API 26 there are no adaptive icons; fall back to the app icon.
const LEGACY_ICON_ALIAS = `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <item name="${ICON}" type="mipmap">@mipmap/ic_launcher</item>
</resources>
`;

function madoHomuActivitySource(mainActivity) {
  if (!mainActivity.includes("class MainActivity")) {
    throw new Error("withAndroidMadoHomuLauncher: MainActivity class declaration not found.");
  }
  const delegate = /object\s*:\s*DefaultReactActivityDelegate\([^)]*\)\s*\{/;
  if (!delegate.test(mainActivity)) {
    throw new Error(
      "withAndroidMadoHomuLauncher: could not find the DefaultReactActivityDelegate in MainActivity — the Expo template changed; update the plugin anchors.",
    );
  }
  let source = mainActivity
    .replace(/class MainActivity\b/, `class ${ACTIVITY_CLASS}`)
    .replace(
      delegate,
      (match) =>
        `${match}\n          override fun getLaunchOptions(): Bundle = Bundle().apply { putString("launchSurface", "${LAUNCH_SURFACE}") }`,
    );
  if (!/^import android\.os\.Bundle$/m.test(source)) {
    source = source.replace(/^(package [^\n]+\n)/, "$1\nimport android.os.Bundle\n");
  }
  return `// Generated by withAndroidMadoHomuLauncher from MainActivity.kt; do not edit.\n${source}`;
}

function withTaskReporting(source) {
  const focus = source.includes(REPORT_WINDOW_FOCUS)
    ? ""
    : `
  override fun onWindowFocusChanged(hasFocus: Boolean) {
    super.onWindowFocusChanged(hasFocus)
    if (hasFocus) ${REPORT_WINDOW_FOCUS}
  }
`;
  const back = source.includes(REPORT_BACK)
    ? ""
    : `
  @Suppress("DEPRECATION", "OVERRIDE_DEPRECATION")
  override fun onBackPressed() {
    if (!${REPORT_BACK}) invokeDefaultOnBackPressed()
  }
`;
  if (!focus && !back) return source;

  const declaration = "class MainActivity : ReactActivity() {";
  if (!source.includes(declaration)) {
    throw new Error(
      "withAndroidMadoHomuLauncher: could not add window focus reporting to MainActivity.",
    );
  }
  const contents = focus
    ? source.replace(
        /^(package [^\n]+\n)/,
        "$1\nimport expo.modules.t3nativecontrols.T3MadoHomuLauncherModule\n",
      )
    : source;
  return contents.replace(declaration, `${declaration}${focus}${back}`);
}

function withMadoHomuManifest(config) {
  return withAndroidManifest(config, (nextConfig) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(nextConfig.modResults);
    const main = AndroidConfig.Manifest.getMainActivityOrThrow(nextConfig.modResults);
    const pkg = AndroidConfig.Package.getPackage(nextConfig) ?? "app";
    const copied = {};
    for (const key of [
      "android:configChanges",
      "android:theme",
      "android:windowSoftInputMode",
      "android:screenOrientation",
      "android:resizeableActivity",
    ]) {
      if (main.$[key] !== undefined) copied[key] = main.$[key];
    }
    const activity = {
      $: {
        "android:name": `.${ACTIVITY_CLASS}`,
        ...copied,
        "android:label": "MadoHomu",
        "android:icon": `@mipmap/${ICON}`,
        "android:roundIcon": `@mipmap/${ICON}`,
        "android:taskAffinity": `${pkg}.madohomu`,
        "android:launchMode": "singleTask",
        "android:exported": "true",
        "android:enabled": "false",
      },
      "intent-filter": [
        {
          action: [{ $: { "android:name": "android.intent.action.MAIN" } }],
          category: [{ $: { "android:name": "android.intent.category.LAUNCHER" } }],
        },
      ],
    };
    application.activity = (application.activity ?? []).filter(
      (entry) => entry.$["android:name"] !== `.${ACTIVITY_CLASS}`,
    );
    application.activity.push(activity);
    return nextConfig;
  });
}

module.exports = function withAndroidMadoHomuLauncher(config) {
  config = withMadoHomuManifest(config);
  config = withAndroidColors(config, (nextConfig) => {
    nextConfig.modResults = AndroidConfig.Colors.assignColorValue(nextConfig.modResults, {
      name: ICON_BACKGROUND_COLOR,
      value: "#E5679B",
    });
    return nextConfig;
  });
  config = withDangerousMod(config, [
    "android",
    (nextConfig) => {
      const res = NodePath.join(nextConfig.modRequest.platformProjectRoot, "app/src/main/res");
      const anydpi = NodePath.join(res, "mipmap-anydpi-v26");
      const values = NodePath.join(res, "values");
      NodeFS.mkdirSync(anydpi, { recursive: true });
      NodeFS.mkdirSync(values, { recursive: true });
      NodeFS.writeFileSync(NodePath.join(anydpi, `${ICON}.xml`), ADAPTIVE_ICON);
      NodeFS.writeFileSync(NodePath.join(values, "madohomu_launcher.xml"), LEGACY_ICON_ALIAS);
      return nextConfig;
    },
  ]);
  // Mods run in reverse registration order, so registering this plugin before the other
  // MainActivity plugins lets this callback copy their finished MainActivity.
  return withMainActivity(config, (nextConfig) => {
    if (nextConfig.modResults.language !== "kt") {
      throw new Error("withAndroidMadoHomuLauncher: MainActivity must be Kotlin.");
    }
    const target = NodePath.join(
      NodePath.dirname(nextConfig.modResults.path),
      `${ACTIVITY_CLASS}.kt`,
    );
    const contents = withTaskReporting(nextConfig.modResults.contents);
    NodeFS.writeFileSync(target, madoHomuActivitySource(contents));
    nextConfig.modResults.contents = contents;
    return nextConfig;
  });
};

module.exports.madoHomuActivitySource = madoHomuActivitySource;
